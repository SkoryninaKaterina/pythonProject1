def analyze_text(input_file, output_file):
    try:
        with open(input_file, "r", encoding="utf-8") as file:
            text = file.read()

        # Підрахунок статистики
        num_chars = len(text)  # Кількість символів
        num_lines = text.count("\n") + 1  # Кількість рядків
        num_digits = sum(c.isdigit() for c in text)  # Кількість цифр
        num_vowels = sum(c.lower() in "aeuio" for c in text)  # Кількість голосних літер


        report = (
            f"Кількість символів: {num_chars}\n"
            f"Кількість рядків: {num_lines}\n"
            f"Кількість цифр: {num_digits}\n"
            f"Кількість голосних літер: {num_vowels}\n"
        )

        # Запис у вихідний файл
        with open(output_file, "w", encoding="utf-8") as out_file:
            out_file.write(report)

        print("✅ Статистика успішно збережена в", output_file)

    except FileNotFoundError:
        print("❌ Помилка: Вхідний файл не знайдено.")


